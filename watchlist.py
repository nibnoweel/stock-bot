# ── 편의 함수 ──────────────────────────────────

def all_codes() -> list[str]:
    """전체 종목코드 (중복 제거)"""
    codes = []
    for stocks in WATCHLIST.values():
        codes.extend(stocks.keys())
    return list(dict.fromkeys(codes))   # 순서 유지하며 중복 제거


def code_to_name() -> dict[str, str]:
    """{코드: 이름} 평탄화 딕셔너리"""
    result = {}
    for stocks in WATCHLIST.values():
        result.update(stocks)
    return result


def code_to_theme() -> dict[str, str]:
    """{코드: 테마명} — 종목이 어느 테마인지"""
    result = {}
    for theme, stocks in WATCHLIST.items():
        for code in stocks:
            result.setdefault(code, theme)   # 중복 시 첫 테마 유지
    return result